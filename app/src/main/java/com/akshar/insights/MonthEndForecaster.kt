package com.akshar.insights

import com.akshar.data.model.Account
import com.akshar.data.model.RecurringTransaction
import com.akshar.data.model.Transaction
import java.math.BigDecimal
import java.math.RoundingMode
import java.util.Calendar
import java.util.TimeZone

sealed interface MonthEndForecast {
    /** Initial loading state before the on-device data arrives. */
    data object NoData : MonthEndForecast

    /** Some history, but too little for a fair daily average yet. */
    data class NotEnoughData(val moreDaysNeeded: Int) : MonthEndForecast

    data class Ready(
        /** Midnight at the start of the month's last day, for the "on 30 Nov" label. */
        val monthEndDayMs: Long,
        val currentBalance: BigDecimal,
        /** Reminders and future-dated entries that land after now and before month end. */
        val upcoming: List<UpcomingItem>,
        val upcomingIncome: BigDecimal,
        val upcomingBills: BigDecimal,
        /** Robust everyday spending per day; see [MonthEndForecaster]. */
        val dailyVariableSpend: BigDecimal,
        val expectedVariableSpend: BigDecimal,
        /** Days of everyday spending still to come, counting today when it is not used up yet. */
        val remainingDays: Int,
        val basedOnDays: Int,
        val excludedLargeCount: Int,
        val excludedLargeTotal: BigDecimal,
        val projectedBalance: BigDecimal,
    ) : MonthEndForecast {
        val isShortfall: Boolean get() = projectedBalance.signum() < 0
    }
}

data class UpcomingItem(
    val description: String,
    /** Positive magnitude; [isIncome] carries the direction. */
    val amount: BigDecimal,
    val isIncome: Boolean,
    val dueMs: Long,
)

/**
 * Projects the total balance at the end of the current month, entirely on the device.
 *
 * projected = balance now + upcoming income − upcoming bills − expected everyday spending
 *
 * - **Balance now**: every account's opening balance plus all ledger entries dated up to now.
 *   Transfers move money between accounts, so both legs are counted and cancel out.
 * - **Upcoming**: each reminder's occurrences after its last trigger up to the end of the month
 *   (the app posts these to the ledger as they come due, so none are in the balance yet), plus
 *   entries the user dated in the future within this month.
 * - **Everyday spending**: expenses from the last [lookbackDays] full days before today (or since
 *   the first entry, if that is more recent). Transfers and entries generated by reminders are
 *   skipped, since bills are already counted above. Large one-off amounts such as rent or a new
 *   phone are left out when they exceed max(Q3 + 3 × IQR, 5 × median) of the expense amounts in
 *   that window (Tukey's "far out" fence with a floor so a quiet month cannot flag a normal
 *   purchase). The rest is summed and divided by the number of days in the window, including days
 *   with no spending, to give a daily rate. That rate applies to each day after today; for today
 *   only the part not already spent is added.
 *
 * Needs at least [minHistoryDays] days of history and [minExpenses] everyday expenses; otherwise
 * it reports [MonthEndForecast.NotEnoughData]. The daily rate keeps 10 decimal places HALF_UP.
 * Monetary breakdown components are rounded to 2 decimals HALF_UP before the final projection,
 * so the displayed balance, income, bills and variable spending reconcile exactly.
 */
class MonthEndForecaster(
    private val timeZone: TimeZone = TimeZone.getDefault(),
    private val lookbackDays: Int = 56,
    private val minHistoryDays: Int = 14,
    private val minExpenses: Int = 5,
) {
    init {
        require(lookbackDays >= minHistoryDays && minHistoryDays > 0)
        require(minExpenses > 0)
    }

    fun forecast(
        nowMs: Long,
        accounts: List<Account>,
        transactions: List<Transaction>,
        reminders: List<RecurringTransaction>,
    ): MonthEndForecast {
        val ledger = transactions.filter { it.amount.isFinite() }

        val todayIndex = InsightMath.dayIndex(nowMs, timeZone)
        val firstDayIndex = ledger.filter { it.transferId == null && it.date <= nowMs }
            .minOfOrNull { InsightMath.dayIndex(it.date, timeZone) }
        val historyDays = if (firstDayIndex == null) 0 else (todayIndex - firstDayIndex).toInt().coerceAtLeast(0)
        if (historyDays < minHistoryDays) {
            return MonthEndForecast.NotEnoughData(moreDaysNeeded = minHistoryDays - historyDays)
        }

        val reminderKeys = reminders.map { MerchantKey.normalize(it.description) }.filter { it.isNotEmpty() }
        fun isEverydayExpense(tx: Transaction): Boolean =
            tx.transferId == null &&
                tx.type.equals("EXPENSE", ignoreCase = true) &&
                tx.amount > 0.0 &&
                !MerchantKey.isReminderGenerated(tx.description) &&
                reminderKeys.none { MerchantKey.sameMerchant(it, MerchantKey.normalize(tx.description)) }

        val windowDays = minOf(lookbackDays, historyDays)
        val windowStartIndex = todayIndex - windowDays
        val windowExpenses = ledger.filter {
            it.date <= nowMs && isEverydayExpense(it) &&
                InsightMath.dayIndex(it.date, timeZone).let { d -> d >= windowStartIndex && d < todayIndex }
        }
        if (windowExpenses.size < minExpenses) {
            return MonthEndForecast.NotEnoughData(moreDaysNeeded = 0)
        }

        val amounts = windowExpenses.map { InsightMath.money(it.amount) }.sorted()
        val fence = largeSpendFence(amounts)
        val kept = amounts.filter { it <= fence }
        val excluded = amounts.filter { it > fence }
        val daily = kept.fold(BigDecimal.ZERO, BigDecimal::add)
            .divide(BigDecimal(windowDays), 10, RoundingMode.HALF_UP)

        val spentToday = ledger.filter {
            it.date <= nowMs && isEverydayExpense(it) && InsightMath.dayIndex(it.date, timeZone) == todayIndex
        }.map { InsightMath.money(it.amount) }.filter { it <= fence }.fold(BigDecimal.ZERO, BigDecimal::add)

        val monthEndMs = InsightMath.endOfMonth(nowMs, timeZone)
        val daysAfterToday = (InsightMath.dayIndex(monthEndMs, timeZone) - todayIndex).toInt()
        val todayRemainder = daily.subtract(spentToday).max(BigDecimal.ZERO)
        val expectedVariable = daily.multiply(BigDecimal(daysAfterToday)).add(todayRemainder)
        val remainingDays = daysAfterToday + if (todayRemainder.signum() > 0) 1 else 0

        val balance = currentBalance(nowMs, accounts, ledger)

        val upcoming = (reminderOccurrences(reminders, nowMs, monthEndMs) + futureEntries(ledger, nowMs, monthEndMs))
            .sortedWith(compareBy<UpcomingItem> { it.dueMs }.thenBy { it.description })
        val upcomingIncome = upcoming.filter { it.isIncome }.fold(BigDecimal.ZERO) { acc, i -> acc.add(i.amount) }
        val upcomingBills = upcoming.filter { !it.isIncome }.fold(BigDecimal.ZERO) { acc, i -> acc.add(i.amount) }

        val projected = InsightMath.roundMoney(balance).add(InsightMath.roundMoney(upcomingIncome))
            .subtract(InsightMath.roundMoney(upcomingBills)).subtract(InsightMath.roundMoney(expectedVariable))
        return MonthEndForecast.Ready(
            monthEndDayMs = InsightMath.startOfLastDayOfMonth(nowMs, timeZone),
            currentBalance = InsightMath.roundMoney(balance),
            upcoming = upcoming,
            upcomingIncome = InsightMath.roundMoney(upcomingIncome),
            upcomingBills = InsightMath.roundMoney(upcomingBills),
            dailyVariableSpend = InsightMath.roundMoney(daily),
            expectedVariableSpend = InsightMath.roundMoney(expectedVariable),
            remainingDays = remainingDays,
            basedOnDays = windowDays,
            excludedLargeCount = excluded.size,
            excludedLargeTotal = InsightMath.roundMoney(excluded.fold(BigDecimal.ZERO, BigDecimal::add)),
            projectedBalance = InsightMath.roundMoney(projected),
        )
    }

    private fun reminderOccurrences(reminders: List<RecurringTransaction>, nowMs: Long, monthEndMs: Long): List<UpcomingItem> =
        reminders.filter { it.amount.isFinite() && it.amount != 0.0 }.flatMap { rec ->
            // A reminder that never fired starts its schedule at the next launch, so from now.
            val anchor = if (rec.lastTriggered == 0L) nowMs else rec.lastTriggered
            val isIncome = rec.type.equals("INCOME", ignoreCase = true) == (rec.amount > 0)
            buildList {
                val count = periodsThrough(anchor, rec.frequency, monthEndMs)
                // Keep the list bounded without dropping money from long-stale reminders.
                val grouped = (count - MAX_OCCURRENCES).coerceAtLeast(0)
                if (grouped > 0) {
                    add(UpcomingItem("${rec.description} · $grouped overdue occurrences",
                        InsightMath.money(rec.amount).abs().multiply(BigDecimal(grouped)), isIncome,
                        InsightMath.addPeriods(anchor, rec.frequency, grouped, timeZone)))
                }
                var step = grouped + 1
                while (step <= count) {
                    val due = InsightMath.addPeriods(anchor, rec.frequency, step, timeZone)
                    if (due > monthEndMs) break
                    add(UpcomingItem(rec.description, InsightMath.money(rec.amount).abs(), isIncome, due))
                    step++
                }
            }
        }

    private fun futureEntries(ledger: List<Transaction>, nowMs: Long, monthEndMs: Long): List<UpcomingItem> =
        ledger.filter { it.date in (nowMs + 1)..monthEndMs && it.transferId == null }.map {
            UpcomingItem(
                description = it.description,
                amount = InsightMath.money(it.amount).abs(),
                isIncome = signed(it).signum() > 0,
                dueMs = it.date,
            )
        }

    /** Count calendar occurrences directly, including overdue charges not posted yet. */
    private fun periodsThrough(anchor: Long, frequency: String, end: Long): Int {
        if (anchor >= end) return 0
        val startCal = InsightMath.calendar(anchor, timeZone)
        val endCal = InsightMath.calendar(end, timeZone)
        val years = endCal.get(Calendar.YEAR) - startCal.get(Calendar.YEAR)
        val days = InsightMath.dayIndex(end, timeZone) - InsightMath.dayIndex(anchor, timeZone)
        var count = when (frequency.uppercase(java.util.Locale.ROOT)) {
            "DAILY" -> days.toInt()
            "WEEKLY" -> (days / 7).toInt()
            "YEARLY" -> years
            else -> years * 12 + endCal.get(Calendar.MONTH) - startCal.get(Calendar.MONTH)
        }.coerceAtLeast(0)
        while (count > 0 && InsightMath.addPeriods(anchor, frequency, count, timeZone) > end) count--
        while (InsightMath.addPeriods(anchor, frequency, count + 1, timeZone) <= end) count++
        return count
    }

    companion object {
        /** Total of account openings and posted ledger entries, including cancelling transfers. */
        fun currentBalance(nowMs: Long, accounts: List<Account>, transactions: List<Transaction>): BigDecimal =
            InsightMath.roundMoney(accounts.fold(BigDecimal.ZERO) { acc, a -> acc.add(InsightMath.money(a.openingBalance)) }
                .add(transactions.filter { it.date <= nowMs && it.amount.isFinite() }
                    .fold(BigDecimal.ZERO) { acc, tx -> acc.add(signed(tx)) }))

        private fun signed(tx: Transaction): BigDecimal {
            val amount = InsightMath.money(tx.amount)
            return if (tx.type.equals("INCOME", ignoreCase = true)) amount else amount.negate()
        }

        /** Guards against a long-stale DAILY reminder producing an unbounded list. */
        private const val MAX_OCCURRENCES = 400

        /** max(Q3 + 3 × IQR, 5 × median) over [sortedAmounts]; anything above is a one-off. */
        fun largeSpendFence(sortedAmounts: List<BigDecimal>): BigDecimal {
            if (sortedAmounts.isEmpty()) return BigDecimal.ZERO
            val q1 = InsightMath.quantile(sortedAmounts, 0.25)
            val median = InsightMath.quantile(sortedAmounts, 0.5)
            val q3 = InsightMath.quantile(sortedAmounts, 0.75)
            val tukey = q3.add(q3.subtract(q1).multiply(BigDecimal(3)))
            return tukey.max(median.multiply(BigDecimal(5)))
        }
    }
}
